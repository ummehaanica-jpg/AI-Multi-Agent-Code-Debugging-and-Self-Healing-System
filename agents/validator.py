"""
Agent 7 — Validator Agent

Validates repaired Python code.

Validation stages:
1. Syntax check (AST parse — no execution)
2. Runtime execution in subprocess with timeout
3. Optional: run generated test code
4. Build a comprehensive validation summary

IMPORTANT:
    A repair is only accepted when this agent returns valid=True.
    Code change alone is NOT proof that a repair worked.

SECURITY:
    All execution happens in a subprocess with timeout.
    Temporary files are always cleaned up.
    Never execute code inside the main Streamlit/orchestrator process.

For production deployment, isolate execution in a Docker container.
"""
from __future__ import annotations

import ast
import os
import subprocess
import sys
import tempfile
import logging
from typing import Any

logger = logging.getLogger(__name__)

DEFAULT_TIMEOUT = 5


def validate_code(
    code: str,
    test_code: str = "",
    timeout: int = DEFAULT_TIMEOUT,
) -> dict[str, Any]:
    """
    Validate repaired Python code.

    Parameters
    ----------
    code:
        The repaired Python source code to validate.
    test_code:
        Optional runnable test script generated by Test Generator Agent.
    timeout:
        Maximum seconds allowed for subprocess execution.

    Returns
    -------
    dict with fields:
        valid               : bool  — True only when all applicable checks pass
        syntax_valid        : bool
        execution_success   : bool
        tests_passed        : bool  — True if test_code ran and all tests passed
        stdout              : str
        stderr              : str
        test_stdout         : str
        test_stderr         : str
        exit_code           : int
        timed_out           : bool
        error_type          : str
        error_message       : str
        validation_summary  : str
    """
    result: dict[str, Any] = {
        "valid": False,
        "syntax_valid": False,
        "execution_success": False,
        "tests_passed": False,
        "stdout": "",
        "stderr": "",
        "test_stdout": "",
        "test_stderr": "",
        "exit_code": -1,
        "timed_out": False,
        "error_type": "",
        "error_message": "",
        "validation_summary": "",
        # Backward compat with old validator
        "success": False,
        "returncode": -1,
    }

    # ============================================================
    # STAGE 1: Syntax Check
    # ============================================================
    try:
        ast.parse(code)
        result["syntax_valid"] = True
    except SyntaxError as exc:
        result["syntax_valid"] = False
        result["error_type"] = "SyntaxError"
        result["error_message"] = str(exc.msg)
        result["validation_summary"] = (
            f"FAIL: Syntax error in repaired code at line {exc.lineno}: {exc.msg}"
        )
        logger.info("Validator: syntax check failed: %s", exc)
        return result  # Cannot run code with syntax error

    # ============================================================
    # STAGE 2: Runtime Execution
    # ============================================================
    exec_result = _run_subprocess(code, timeout)
    result.update({
        "stdout": exec_result["stdout"],
        "stderr": exec_result["stderr"],
        "exit_code": exec_result["exit_code"],
        "timed_out": exec_result["timed_out"],
        "returncode": exec_result["exit_code"],  # backward compat
    })

    if exec_result["timed_out"]:
        result["execution_success"] = False
        result["error_type"] = "TimeoutError"
        result["error_message"] = f"Code execution timed out after {timeout}s."
        result["validation_summary"] = (
            f"FAIL: Code execution timed out after {timeout}s. "
            "Possible infinite loop."
        )
        return result

    if exec_result["exit_code"] != 0:
        result["execution_success"] = False
        # Extract error from stderr
        error_type, error_msg = _extract_error(exec_result["stderr"])
        result["error_type"] = error_type
        result["error_message"] = error_msg
        result["validation_summary"] = (
            f"FAIL: Code execution failed. {error_type}: {error_msg}"
        )
        logger.info(
            "Validator: execution failed. exit=%s stderr=%s",
            exec_result["exit_code"],
            exec_result["stderr"][:200],
        )
        return result

    result["execution_success"] = True
    result["success"] = True  # backward compat

    # ============================================================
    # STAGE 3: Test Execution (if test_code available)
    # ============================================================
    if test_code and test_code.strip():
        combined_test_code = code.rstrip() + "\n\n" + test_code
        test_exec = _run_subprocess(combined_test_code, timeout)
        result["test_stdout"] = test_exec["stdout"]
        result["test_stderr"] = test_exec["stderr"]

        if test_exec["timed_out"]:
            result["tests_passed"] = False
            result["validation_summary"] = (
                "FAIL: Test execution timed out."
            )
            result["valid"] = False
            return result

        if test_exec["exit_code"] == 0:
            result["tests_passed"] = True
            result["valid"] = True
            result["validation_summary"] = (
                "PASS: Code executes successfully and all generated tests passed."
            )
        else:
            result["tests_passed"] = False
            result["valid"] = False
            result["validation_summary"] = (
                "PARTIAL: Code executes but generated tests failed. "
                "Possible logical error or incorrect repair."
            )
        return result

    # No test code — validity is based on execution success alone
    result["tests_passed"] = True  # no tests to fail
    result["valid"] = True
    result["validation_summary"] = (
        "PASS: Code executes successfully. No generated tests available."
    )
    return result


# ================================================================
# SUBPROCESS RUNNER
# ================================================================


def _run_subprocess(
    code: str,
    timeout: int,
) -> dict[str, Any]:
    """Run code in a subprocess and return stdout, stderr, exit_code."""
    tmp_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            suffix=".py",
            delete=False,
            encoding="utf-8",
        ) as tmp:
            tmp.write(code)
            tmp_path = tmp.name

        proc = subprocess.run(
            [sys.executable, tmp_path],
            capture_output=True,
            text=True,
            timeout=timeout,
            stdin=subprocess.DEVNULL,
            cwd=os.path.dirname(tmp_path),
        )
        return {
            "stdout": proc.stdout.strip(),
            "stderr": proc.stderr.strip(),
            "exit_code": proc.returncode,
            "timed_out": False,
        }

    except subprocess.TimeoutExpired as exc:
        stdout = ""
        if isinstance(exc.stdout, bytes):
            stdout = exc.stdout.decode("utf-8", errors="replace")
        elif isinstance(exc.stdout, str):
            stdout = exc.stdout
        return {
            "stdout": stdout.strip(),
            "stderr": f"Execution timed out after {timeout}s.",
            "exit_code": -1,
            "timed_out": True,
        }
    except Exception as exc:
        return {
            "stdout": "",
            "stderr": str(exc),
            "exit_code": -1,
            "timed_out": False,
        }
    finally:
        if tmp_path and os.path.exists(tmp_path):
            try:
                os.unlink(tmp_path)
            except OSError:
                pass


# ================================================================
# ERROR EXTRACTION
# ================================================================


def _extract_error(stderr: str) -> tuple[str, str]:
    """Extract error type and message from a Python traceback."""
    import re
    if not stderr:
        return "RuntimeError", "Unknown error."
    pattern = re.compile(
        r"^(?P<type>[A-Za-z_][A-Za-z0-9_]*(?:Error|Exception)):\s*(?P<msg>.*)$"
    )
    for line in reversed(stderr.splitlines()):
        match = pattern.match(line.strip())
        if match:
            return match.group("type"), match.group("msg").strip()
    return "RuntimeError", stderr.splitlines()[-1] if stderr.splitlines() else "Unknown error."
